"""Figures and the generated model card. Every number comes from the run that wrote the file."""

from __future__ import annotations

from pathlib import Path
from typing import Any

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

ACCENT, MUTED, INK, SECONDARY, SURFACE, GRID = (
    "#2a78d6", "#8b8a84", "#0b0b0b", "#52514e", "#fcfcfb", "#e7e6e1",
)  # fmt: skip


def _style(ax: Any) -> None:
    ax.set_facecolor(SURFACE)
    ax.figure.set_facecolor(SURFACE)
    for side in ("top", "right", "left"):
        ax.spines[side].set_visible(False)
    ax.spines["bottom"].set_color(GRID)
    ax.tick_params(colors=SECONDARY, length=0, labelsize=10)
    ax.xaxis.label.set_color(SECONDARY)
    ax.yaxis.label.set_color(SECONDARY)
    ax.set_axisbelow(True)


def plot_model_comparison(table: pd.DataFrame, selected: str, path: Path) -> None:
    ordered = table.sort_values("mae", ascending=False).reset_index(drop=True)
    fig, ax = plt.subplots(figsize=(8, 0.45 * len(ordered) + 1.6), dpi=200)
    _style(ax)
    for row in ordered.itertuples():
        color = ACCENT if row.model == selected else MUTED
        ax.plot([row.mae_ci_low, row.mae_ci_high], [row.Index] * 2, color=color, lw=2,
                solid_capstyle="round")  # fmt: skip
        ax.plot(row.mae, row.Index, "o", color=color, ms=8, mec=SURFACE, mew=2)
    labels = [f"{m} (selected)" if m == selected else m for m in ordered["model"]]
    ax.set_yticks(range(len(ordered)), labels)
    ax.grid(axis="x", color=GRID, lw=0.8)
    ax.set_xlabel("Mean absolute error, years (lower is better)")
    ax.set_title("Error on held-out landings, with 95% landing-bootstrap intervals",
                 loc="left", color=INK, fontsize=12)  # fmt: skip
    fig.tight_layout()
    fig.savefig(path)
    plt.close(fig)


def plot_calibration(
    y_true: np.ndarray, y_pred: np.ndarray, lower: np.ndarray, upper: np.ndarray, path: Path,
    min_fish: int = 10,
) -> None:  # fmt: skip
    frame = pd.DataFrame({"age": y_true, "pred": y_pred, "low": lower, "high": upper})
    grouped = frame.groupby("age").agg(
        n=("pred", "size"), pred=("pred", "mean"), low=("low", "mean"), high=("high", "mean")
    )
    grouped = grouped[grouped["n"] >= min_fish]
    fig, ax = plt.subplots(figsize=(8, 5), dpi=200)
    _style(ax)
    limit = float(grouped["high"].max()) + 1
    ax.plot([0, limit], [0, limit], color=MUTED, lw=1.5, ls=(0, (4, 3)))
    ax.annotate("perfect agreement", xy=(limit * 0.72, limit * 0.72), xytext=(-8, 8),
                textcoords="offset points", color=SECONDARY, fontsize=10, ha="right")  # fmt: skip
    ax.fill_between(grouped.index, grouped["low"], grouped["high"], color=ACCENT, alpha=0.14, lw=0)
    ax.plot(grouped.index, grouped["pred"], "-o", color=ACCENT, lw=2, ms=7, mec=SURFACE, mew=2)
    ax.grid(color=GRID, lw=0.8)
    ax.set_xlabel("Scale-read age, years")
    ax.set_ylabel("Predicted age, years")
    ax.set_title(f"Mean prediction by age with average 90% interval (ages with {min_fish}+ fish)",
                 loc="left", color=INK, fontsize=12)  # fmt: skip
    fig.tight_layout()
    fig.savefig(path)
    plt.close(fig)


def _markdown_table(frame: pd.DataFrame) -> str:
    def cell(value: Any) -> str:
        return f"{value:.3f}" if isinstance(value, float) else str(value)

    header = "| " + " | ".join(frame.columns) + " |"
    rule = "|" + "---|" * len(frame.columns)
    rows = ["| " + " | ".join(cell(v) for v in row) + " |" for row in frame.to_numpy().tolist()]
    return "\n".join([header, rule, *rows])


def write_model_card(
    path: Path,
    results: dict[str, Any],
    quality: dict[str, Any],
    test_table: pd.DataFrame,
    slices: pd.DataFrame,
) -> None:
    checks = results["promotion_checks"]
    delta, coverage = checks["mae_difference_vs_reference"], checks["interval_coverage"]
    columns = ["model", "mae", "mae_ci_low", "mae_ci_high", "bias", "within_1yr_rate", "qwk"]
    temporal = pd.DataFrame(results["temporal_check"])
    temporal_text = _markdown_table(temporal[[
        "model", "train_n", "n", "mae", "bias", "mae_gears_seen_in_training"
    ]]) if not temporal.empty else "Not available."  # fmt: skip
    split = results["split"]
    text = f"""# Model card: Pagrus pagrus age from dockside measurements

Generated by run `{results["run_id"]}`. Do not edit by hand.

**Selected model:** `{results["selected_model"]}`. **Promoted:** {results["promoted"]}.

## Intended use
Estimate the scale-read age of red porgy landed in Rio Grande, Brazil, in 1976-1985, when
scales are unavailable or unreadable. It is a research tool for that historical stock.

## Not for
- Current stock assessment: the data end in 1985, and exploitation rose sharply during the series.
- Individual fish decisions, or other regions and species.

## Target caveat
The target is **scale-read** age, not true age. Haimovici et al. (2020) report 53% exact and 40%
one-year agreement between scales and otoliths on 89 fish, and scales under-read older fish.
This model learns those reading errors too.

## Data
{quality["rows_out"]} fish from {quality["landings"]} landings; {quality["aged_fish"]} aged across
{quality["landings_with_aged_fish"]} landings. Split by landing and stratified by gear:
{split["dev_fish"]} fish in {split["dev_landings"]} development landings and {split["test_fish"]}
fish in {split["test_landings"]} test landings.

## Held-out results
{_markdown_table(test_table[columns])}

Selected minus `{checks["reference_model"]}` (age-length key) MAE:
{delta["estimate"]:.3f} years (95% CI {delta["ci_low"]:.3f} to {delta["ci_high"]:.3f}).

Interval coverage: {coverage["estimate"]:.3f} (95% CI {coverage["ci_low"]:.3f} to
{coverage["ci_high"]:.3f}); target {checks["target_coverage"]:.2f}.

## Subgroups (test)
{_markdown_table(slices)}

## Temporal check (fit <=1981, test >=1982)
Handline landings occur only in 1983-84, so this gear is unseen in training here.

{temporal_text}

## Known limits
- Unaged fish are not a random sample: their scales were often unreadable. Accuracy on them cannot
  be measured, and held-out results describe fish whose scales could be read.
- Few independent landings: use the intervals above, not the point estimates alone.
- Sampling gear retains age 1-2 fish poorly, so young ages are under-represented.
- Coordinates are the landing port, so the data hold no spatial information about the catch.
"""
    path.write_text(text, encoding="utf-8")
